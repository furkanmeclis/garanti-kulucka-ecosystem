export type StatusKey = keyof (typeof statusMessages)["tr"];

/** A controller message: a dictionary key (translated when rendered) or raw backend text. */
export type UiMessage = { key: StatusKey; params?: MessageParams } | { text: string };

export function uiMessage(key: StatusKey, params?: MessageParams): UiMessage {
  return params ? { key, params } : { key };
}

export function rawMessage(text: string): UiMessage {
  return { text };
}

/** Renders a `UiMessage` in the current language. */
export function useUiMessageText() {
  const t = useT(statusMessages);
  return (message: UiMessage) => ("text" in message ? message.text : t(message.key, message.params));
}
